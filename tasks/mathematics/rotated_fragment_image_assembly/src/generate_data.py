"""Maintainer synthetic acquisition: exact block extraction and C4 action.

The bound observations were generated by the author's PuzzleFun from its real
16-bit photograph, after the documented aspect crop/resize to 504 by 672.
This module explicitly defines the resulting noiseless forward operator on that
processed image. Original photograph and acquisition permutation are private;
the inverse CLI never imports or reads them. Permutations are supplied as known
acquisition poses, rather than relying on random-seed trajectory matching.
"""
import numpy as np


def acquire(image,positions,quarter_turns,piece_size=28):
    """Extract blocks and apply inverse correcting turns; preserve pixel dtype."""
    image=np.asarray(image);p=np.asarray(positions);q=np.asarray(quarter_turns)
    return np.stack([np.rot90(image[r*piece_size:(r+1)*piece_size,c*piece_size:(c+1)*piece_size],-int(k))
                     for (r,c),k in zip(p,q)])


def adjoint(tiles,positions,quarter_turns):
    """Inverse block permutation for valid complete, collision-free task poses.

    Floating arrays also support linear overlap-add for adjoint controls. Native
    integer arrays are used only with the task's bijective poses; overlapping
    integer additions are outside this function's supported acquisition domain.
    """
    tiles=np.asarray(tiles);p=np.asarray(positions);q=np.asarray(quarter_turns)
    size=tiles.shape[1];height,width=np.max(p,axis=0)+1
    result=np.zeros((height*size,width*size,tiles.shape[-1]),dtype=tiles.dtype)
    for tile,(r,c),k in zip(tiles,p,q):
        result[r*size:(r+1)*size,c*size:(c+1)*size]+=np.rot90(tile,int(k))
    return result
