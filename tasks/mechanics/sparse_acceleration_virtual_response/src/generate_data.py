"""Explicit author-case observation generation, maintainer-only.

Underlying truth is the noiseless full10DOF Newmark response, before the
author's unused post-hoc1e-16variance state perturbation. Acceleration noise
variance is1e-4(m/s^2)^2. The bound observations were generated by the actual
native run; exact regeneration accepts its privately frozen forcing/noise
realizations as explicit arguments. These are never solver inputs.
"""
from pathlib import Path
import argparse,time
import numpy as np
from .preprocessing import load_observations

def simulate(mass,stiffness,damping,force_matrix,forces,dt=.001,initial_displacement=None,initial_velocity=None):
    """Average-acceleration Newmark; return u,v,a[time,dof] in SI units."""
    count=len(forces);ndof=len(mass);gamma=.5;beta=.25
    u=np.zeros((count,ndof));v=np.zeros_like(u);a=np.zeros_like(u)
    if initial_displacement is not None:u[0]=initial_displacement
    if initial_velocity is not None:v[0]=initial_velocity
    a[0]=np.linalg.inv(mass)@(force_matrix@forces[0]-damping@v[0]-stiffness@u[0])
    a1=mass/(beta*dt**2)+gamma/(beta*dt)*damping
    a2=mass/(beta*dt)+(gamma/beta-1)*damping
    a3=(1/(2*beta)-1)*mass+dt*(gamma/(2*beta)-1)*damping
    inverse=np.linalg.inv(stiffness+a1)
    for k in range(count-1):
        rhs=force_matrix@forces[k+1]+a1@u[k]+a2@v[k]+a3@a[k]
        u[k+1]=inverse@rhs
        v[k+1]=gamma/(beta*dt)*(u[k+1]-u[k])+(1-gamma/beta)*v[k]+dt*(1-gamma/(2*beta))*a[k]
        a[k+1]=(u[k+1]-u[k])/(beta*dt**2)-v[k]/(beta*dt)-(1/(2*beta)-1)*a[k]
    return u,v,a

def resample(time,values,new_time):
    """Source-compatible piecewise-linear temporal interpolation per channel."""
    return np.array([np.interp(new_time,time,values[:,k]) for k in range(values.shape[1])]).T

def generate(forcing_path,calibration_path,raw_output,truth_output,noise_path=None,seed=0):
    """Generate full case from explicit private forces and public calibration."""
    started=time.perf_counter();data=load_observations(calibration_path)
    with np.load(forcing_path,allow_pickle=False) as z:forces=z['forces'][0];Sp=z['force_matrix'][0]
    u,v,a=simulate(data['mass'],data['stiffness'],data['damping'],Sp,forces)
    t=np.arange(len(forces))*.001;to=data['observation_time'];tr=data['reconstruction_time']
    observed=resample(t,a@data['sensor_matrix'].T,to)
    if noise_path is None:noise=np.random.default_rng(seed).normal(0,.01,observed.shape)
    else:
        with np.load(noise_path,allow_pickle=False) as z:noise=z['noise'][0]
    if noise.shape!=observed.shape:raise ValueError('Noise realization shape mismatch')
    data['accelerations']=observed+noise
    raw=Path(raw_output);truth=Path(truth_output);raw.parent.mkdir(parents=True,exist_ok=True);truth.parent.mkdir(parents=True,exist_ok=True)
    np.savez_compressed(raw,**{k:x[None] for k,x in data.items()})
    np.savez_compressed(truth,reconstruction=resample(t,u,tr)[None],velocity=resample(t,v,tr)[None],acceleration=resample(t,a,tr)[None])
    return time.perf_counter()-started

def main():
    p=argparse.ArgumentParser();p.add_argument('--forcing',required=True);p.add_argument('--calibration',default='data/raw_data.npz');p.add_argument('--raw-output',required=True);p.add_argument('--truth-output',required=True);p.add_argument('--noise');a=p.parse_args()
    print('Generated full case seconds:',generate(a.forcing,a.calibration,a.raw_output,a.truth_output,a.noise))
if __name__=='__main__':main()
