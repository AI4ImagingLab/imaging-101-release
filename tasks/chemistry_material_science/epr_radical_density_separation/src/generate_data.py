"""Maintainer-only analytical controls and author-defined synthetic generation.

Primary observations were generated by the unchanged author script at commit
2543bae3e1b75dc55f371d773b5a9b758fc51524 before local extraction. The author
uses a300x300 grid, .01cm sampling, a .8cm diameter TAM disk centered at
(-.1,.25)cm, and a1.5x.75cm TEMPO rectangle centered at zero. The public
40 gradients/reference spectra are retained. Independent Gaussian receiver
noise has std5000, RandomState seed20261022. The final inverse uses100x100
nodes/.03cm. This module is never imported by the primary reconstruction.

Direct float64 generation is verified against the separately run original
float64 control at1e-9 relative tolerance and original float32 generation at
1e-5. It does not claim bitwise recreation of original float32 NUFFT arithmetic.
"""
import numpy as np
from .physics_model import EPRModel

def physical_truth(shape=(100,100),delta=.03):
 """Known continuous author shapes sampled at requested centered nodal grid."""
 x=(np.arange(shape[1])-shape[1]//2)*delta;y=(np.arange(shape[0])-shape[0]//2)*delta;X,Y=np.meshgrid(x,y)
 return np.stack([((X+.1)**2+(Y-.25)**2<=.4**2),((abs(X)<=.75)&(abs(Y)<=.375))]).astype(np.float64)

def generate_author_observations(calibration,seed=20261022,noise_std=5000.):
 """Compute full fine-grid forward model and receiver noise, without domain libs."""
 truth=physical_truth((300,300),.01)
 model=EPRModel(calibration['magnetic_field_G'],calibration['gradients_G_cm'],calibration['reference_spectra'],delta=.01,shape=(300,300))
 clean=model.project(truth)
 noise=np.random.RandomState(seed).normal(loc=0.,scale=noise_std,size=clean.shape).astype(np.float32)
 return dict(clean=clean,noise=noise,observed=clean+noise,truth=truth)

def noise_variants(clean,noise,scales=(.5,1.,2.)):
 """Maintenance sensitivity only: one fixed realization, changed noise amplitude."""
 return np.stack([np.asarray(clean,dtype=float)+float(s)*np.asarray(noise,dtype=float) for s in scales])
