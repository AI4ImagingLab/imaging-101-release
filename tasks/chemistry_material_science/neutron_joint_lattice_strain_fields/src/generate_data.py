    normals=np.c_[np.zeros(100),np.r_[np.ones(50),-np.ones(50)]]
    return {'observations':clean+4.056e-4*rng.standard_normal(len(clean)),'entry':e,'exit':x,'direction':n,'path_length':length,'grid_x':gx,'grid_y':gy,'traction_points':np.c_[tx,ty],'traction_normals':normals}
